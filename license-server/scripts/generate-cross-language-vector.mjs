#!/usr/bin/env node
/**
 * One-time generator for the committed cross-language test vector:
 * test/vectors/ed25519-cross-language.json
 *
 * Why this exists (ecommerce readiness spec, criterion D1): the License Server
 * issues licenses from a Cloudflare Worker — Workers' WebCrypto, not
 * PyCryptodome. The whole build rests on a Worker-signed string verifying
 * under the UNMODIFIED homeschool-api/core/licensing.py::verify_license. The
 * committed vector is that proof: a fixed TEST-ONLY keypair, a fixed payload,
 * and the signature over it. Ed25519 signing is deterministic (RFC 8032), so
 * the same key + bytes produce the same signature forever:
 *
 *   - license-server's own vitest suite (run inside workerd) re-signs the
 *     fixture payload and asserts byte-equality with the committed signature —
 *     proving the PEM→PKCS#8 import + sign path under the actual Workers
 *     runtime.
 *   - homeschool-api/tests/test_license_server_cross_language.py verifies the
 *     committed license_key through the real Python verifier — proving the
 *     cross-language contract.
 *
 * Regenerating replaces the keypair and signature together (a new vector);
 * nothing production ever depends on this keypair — it is throwaway, marked
 * as such in the JSON, and its private half buys an attacker nothing (it
 * cannot license anyone against the REAL embedded public key).
 *
 * Usage: npm run generate-cross-language-vector  (from license-server/)
 */
import { webcrypto as crypto } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = join(here, "..", "test", "vectors");
const OUT = join(OUT_DIR, "ed25519-cross-language.json");
// The same vector as a TS module: the workerd runtime test cannot import
// JSON (no fs, no json loader in the pool), so the generator emits BOTH —
// one source, two formats, zero drift.

// Fixed values — the point is a STABLE vector, not randomness. Changing any
// of these means regenerating the whole file (fresh signature included).
const PAYLOAD = {
  id: "6f6a1c66-0e11-4c5e-9a3f-8f2f5a4c9b01",
  licensee: "storefront-test-family@example.com",
  tier: "core",
  seats: 6,
  issued: "2026-10-10",
  expires: "2031-10-09",
};

// Byte-identical to Python's json.dumps(payload, separators=(",", ":"),
// sort_keys=True) for this ASCII-only, string/number/null payload — the exact
// serialization homeschool-api/scripts/issue_license.py signs with.
function canonicalDumps(payload) {
  const keys = Object.keys(payload).sort();
  const parts = keys.map((k) => {
    const v = payload[k];
    if (v === null) return `${JSON.stringify(k)}:null`;
    if (typeof v === "number") return `${JSON.stringify(k)}:${v}`;
    return `${JSON.stringify(k)}:${JSON.stringify(v)}`;
  });
  return `{${parts.join(",")}}`;
}

function b64url(bytes) {
  return Buffer.from(bytes).toString("base64url"); // Node's base64url is unpadded
}

function pemWrap(der, label) {
  const b64 = Buffer.from(der).toString("base64");
  const lines = b64.match(/.{1,64}/g).join("\n");
  return `-----BEGIN ${label}-----\n${lines}\n-----END ${label}-----`;
}

const keypair = await crypto.subtle.generateKey("Ed25519", true, ["sign", "verify"]);
const privatePkcs8 = await crypto.subtle.exportKey("pkcs8", keypair.privateKey);
const publicSpki = await crypto.subtle.exportKey("spki", keypair.publicKey);

const privateKeyPem = pemWrap(privatePkcs8, "PRIVATE KEY");
const publicKeyPem = pemWrap(publicSpki, "PUBLIC KEY");

const payloadJson = canonicalDumps(PAYLOAD);
const payloadBytes = new TextEncoder().encode(payloadJson);
const signature = await crypto.subtle.sign("Ed25519", keypair.privateKey, payloadBytes);

const vector = {
  comment:
    "TEST-ONLY throwaway keypair — generated by license-server/scripts/generate-cross-language-vector.mjs. " +
    "NEVER paste a real signing key here: this file is public, and the real private key's public half is " +
    "core/licensing.py's PUBLIC_KEY_PEM (see homeschool-api/tests/test_license_server_cross_language.py, " +
    "which asserts the two differ). See the generator's docstring for what this vector proves (spec D1).",
  public_key_pem: publicKeyPem,
  private_key_pem: privateKeyPem,
  payload: PAYLOAD,
  payload_json: payloadJson,
  payload_json_b64url: b64url(payloadBytes),
  signature_b64url: b64url(new Uint8Array(signature)),
  license_key: `${b64url(payloadBytes)}.${b64url(new Uint8Array(signature))}`,
};

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, JSON.stringify(vector, null, 2) + "\n");
console.log(`wrote ${OUT}`);

// The TS twin — same object, `satisfies` keeps the shape honest.
const tsOut = `/**
 * Generated alongside ed25519-cross-language.json by
 * license-server/scripts/generate-cross-language-vector.mjs — DO NOT EDIT
 * either by hand; regenerate instead. This module exists because the
 * workerd vitest pool cannot import JSON, while the Python cross-language
 * test reads the JSON twin.
 */
export interface CrossLanguageVector {
  comment: string;
  public_key_pem: string;
  private_key_pem: string;
  payload: Record<string, string | number>;
  payload_json: string;
  payload_json_b64url: string;
  signature_b64url: string;
  license_key: string;
}

export const VECTOR: CrossLanguageVector = ${JSON.stringify(vector, null, 2)};
`;
const OUT_TS = join(OUT_DIR, "cross-language.ts");
writeFileSync(OUT_TS, tsOut);
console.log(`wrote ${OUT_TS}`);
console.log(`payload_json: ${payloadJson}`);
console.log(`license_key:  ${vector.license_key}`);
